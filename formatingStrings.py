
# ***** Topic: Formating Strings *****


# Concatenation
name = input("Name: ")
print("Hi, " + name)    
# + sign is used to concatenate
#  In python, the + operator can be used to add numbers or concatenate strings and lists.
# ************************

# Plugin formated strings
name = input("Name: ")
print(f"Hello, {name}")

# Both of these methods are used to format strings in Python. The first method uses concatenation with the + operator, while the second method uses f-strings, which is a more modern and preferred way to format strings in Python.